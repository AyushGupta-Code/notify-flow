"""Turn drill-output/drill-samples.jsonl into a promtool rule test, so the alert rules are
checked against metrics measured in the drill (not hand-written series).

    python scripts/drill_to_promtool.py > deploy/prometheus/alerts_drill_test.yml
"""

import json
from pathlib import Path

STEP = 10  # seconds between replayed points
OUT = Path("drill-output")

samples = [json.loads(line) for line in (OUT / "drill-samples.jsonl").read_text().splitlines()]
summary = json.loads((OUT / "drill-summary.json").read_text())
end = samples[-1]["t"]
points = [min(samples, key=lambda s, t=t: abs(s["t"] - t)) for t in range(0, int(end), STEP)]

series = {}
for key in sorted({k for s in samples for k in s["copy"]}):
    src, reason = key.split(":")
    series[f'nf_copy_generated_total{{source="{src}",reason="{reason}"}}'] = [
        p["copy"].get(key, 0) for p in points
    ]
series['nf_llm_circuit_state{instance="worker-1"}'] = [p["circuit"] for p in points]

ph = summary["phases_s"]
circuit_eval = int(ph["outage_start"] + 150)  # open since ~outage_start, for: 2m
fallback_eval = int(ph["outage_end"] - 10)
print(f"""# Generated by scripts/drill_to_promtool.py from drill run {summary["run"]}
# (LLM killed at {ph["outage_start"]}s, restored at {ph["outage_end"]}s; points every {STEP}s).
rule_files: [alerts.yml]
evaluation_interval: {STEP}s
tests:
  - name: replay of LLM-outage drill {summary["run"]}
    interval: {STEP}s
    input_series:""")
for name, vals in series.items():
    print(f"      - series: '{name}'")
    print(f"        values: '{' '.join(str(int(v)) for v in vals)}'")
print(f"""    alert_rule_test:
      - eval_time: {int(ph["outage_start"]) - 10}s
        alertname: NotifyFlowLLMCircuitOpen
        exp_alerts: []
      - eval_time: {circuit_eval}s
        alertname: NotifyFlowLLMCircuitOpen
        exp_alerts:
          - exp_labels: {{severity: warning, team: proactive-comms}}
            exp_annotations:
              summary: "LLM circuit breaker is open (or half-open) on at least one worker"
              runbook: "docs/RUNBOOK.md#llm-circuit-open"
      # Finding from the drill: a 3-minute outage never satisfies the fallback-rate alert's
      # 'for: 5m', so the circuit alert is the one that catches short provider outages.
      - eval_time: {fallback_eval}s
        alertname: NotifyFlowLLMFallbackRateHigh
        exp_alerts: []""")
